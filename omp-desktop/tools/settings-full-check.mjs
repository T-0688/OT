import { writeFileSync } from "node:fs";
const wait=(ms)=>new Promise(r=>setTimeout(r,ms));
const list=await (await fetch(`http://127.0.0.1:9336/json/list`)).json();
const page=list.find(t=>t.type==="page");
const ws=new WebSocket(page.webSocketDebuggerUrl);
let id=0;const pending=new Map();
ws.onmessage=e=>{const m=JSON.parse(e.data);if(m.id&&pending.has(m.id)){pending.get(m.id)(m.result??m.error);pending.delete(m.id);}};
await new Promise(r=>ws.onopen=r);
const send=(m,p={})=>new Promise(res=>{const i=++id;pending.set(i,res);ws.send(JSON.stringify({id:i,method:m,params:p}));});
const ev=async e=>(await send("Runtime.evaluate",{expression:e,returnByValue:true,awaitPromise:true}))?.result?.value;
await wait(1200);
await ev(`(() => { const b=[...document.querySelectorAll('button')].find(x=>x.textContent.trim()==='设置'); b?.click(); })()`);
await wait(900);
console.log("state =", await ev(`JSON.stringify({view: document.querySelector('.app').dataset.view, sidebar: getComputedStyle(document.querySelector('.sidebar')).display, back: !!document.querySelector('.settings-back')})`));
const shot=await Promise.race([send("Page.captureScreenshot",{format:"png"}),new Promise(r=>setTimeout(()=>r(null),15000))]);
if (shot?.data){writeFileSync("shot-settings-full.png",Buffer.from(shot.data,"base64"));console.log("saved");}
await ev(`document.querySelector('.settings-back')?.click()`);
await wait(600);
console.log("after back =", await ev(`document.querySelector('.app').dataset.view`));
process.exit(0);
