import { writeFileSync } from "node:fs";
const PORT = process.env.PORT || "9337";
const wait = (ms) => new Promise(r => setTimeout(r, ms));
const list = await (await fetch(`http://127.0.0.1:${PORT}/json/list`)).json();
const page = list.find(t => t.type === "page");
const ws = new WebSocket(page.webSocketDebuggerUrl);
let id = 0; const pending = new Map();
ws.onmessage = e => { const m = JSON.parse(e.data); if (m.id && pending.has(m.id)) { pending.get(m.id)(m.result ?? m.error); pending.delete(m.id); } };
await new Promise(r => ws.onopen = r);
const send = (m, p = {}) => new Promise(res => { const i = ++id; pending.set(i, res); ws.send(JSON.stringify({ id: i, method: m, params: p })); });
const ev = async e => (await send("Runtime.evaluate", { expression: e, returnByValue: true, awaitPromise: true }))?.result?.value;
await wait(800);
console.log("init:", await ev(`JSON.stringify({v: document.querySelector('.version')?.textContent, toolDetails: document.querySelectorAll('details.tool').length})`));
await ev(`window.api.prompt('帮我列一个 1 到 30 的数字清单，每行一个数字')`);
await wait(2500);
console.log("live:", await ev(`document.querySelector('.stat.live')?.textContent`));
console.log("stopBtn:", await ev(`(() => { const b=document.querySelector('.send-icon.stop'); return b ? getComputedStyle(b).backgroundColor : 'none'; })()`));
await ev(`document.querySelector('.send-icon.stop')?.click()`);
await wait(800);
const shot = await send("Page.captureScreenshot", { format: "png" });
if (shot?.data) writeFileSync("shot-1.14.png", Buffer.from(shot.data, "base64"));
process.exit(0);
