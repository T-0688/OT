import { writeFileSync } from "node:fs";
const PORT = "9349";
const wait = (ms) => new Promise(r => setTimeout(r, ms));
const list = await (await fetch(`http://127.0.0.1:${PORT}/json/list`)).json();
const page = list.find(t => t.type === "page" && !t.url.includes("ot-shot-overlay"));
const ws = new WebSocket(page.webSocketDebuggerUrl);
let id = 0; const pending = new Map();
ws.onmessage = e => { const m = JSON.parse(e.data); if (m.id && pending.has(m.id)) { pending.get(m.id)(m.result ?? m.error); pending.delete(m.id); } };
await new Promise(r => ws.onopen = r);
const send = (m, p = {}) => new Promise(res => { const i = ++id; pending.set(i, res); ws.send(JSON.stringify({ id: i, method: m, params: p })); });
const ev = async e => (await send("Runtime.evaluate", { expression: e, returnByValue: true, awaitPromise: true }))?.result?.value;
await send("Runtime.enable");
console.log("console errors captured via evaluate");
await ev(`(() => { const b=[...document.querySelectorAll('button')].find(x=>x.textContent.trim()==='设置'); b?.click(); })()`);
await wait(1200);
console.log("panel:", await ev(`JSON.stringify({ has: !!document.querySelector('.panel.settings'), tab: document.querySelector('.panel.settings')?.dataset.tab, navCount: document.querySelectorAll('.settings-nav-item').length, groupCount: document.querySelectorAll('.settings-content .set-group').length, visible: [...document.querySelectorAll('.settings-content .set-group')].filter(s=>getComputedStyle(s).display!=='none').length, text: document.querySelector('.panel.settings')?.innerText.slice(0,120) })`));
const shot = await send("Page.captureScreenshot", { format: "png" });
if (shot?.data) writeFileSync("shot-settings-bug.png", Buffer.from(shot.data, "base64"));
process.exit(0);
