import { writeFileSync } from "node:fs";
const list=await (await fetch(`http://127.0.0.1:9335/json/list`)).json();
const page=list.find(t=>t.type==="page");
const ws=new WebSocket(page.webSocketDebuggerUrl);
let id=0;const pending=new Map();
ws.onmessage=e=>{const m=JSON.parse(e.data);if(m.id&&pending.has(m.id)){pending.get(m.id)(m.result??m.error);pending.delete(m.id);}};
await new Promise(r=>ws.onopen=r);
const send=(m,p={})=>new Promise(res=>{const i=++id;pending.set(i,res);ws.send(JSON.stringify({id:i,method:m,params:p}));});
const ev=async e=>(await send("Runtime.evaluate",{expression:e,returnByValue:true,awaitPromise:true}))?.result?.value;
await ev(`(() => { const b=[...document.querySelectorAll('button')].find(x=>x.textContent.trim()==='设置'); b?.click(); })()`);
await new Promise(r=>setTimeout(r,800));
await ev(`[...document.querySelectorAll('.settings-nav-item')].find(b=>b.textContent.includes('账号与余额'))?.click()`);
await new Promise(r=>setTimeout(r,700));
console.log("key row:", await ev(`(() => { const row=[...document.querySelectorAll('.settings-content .set-row')].find(r=>r.textContent.includes('API Key')); return row ? row.getBoundingClientRect().width + ' | ' + row.innerText.replace(/\\n/g,' / ') : 'missing'; })()`));
const s1=await send("Page.captureScreenshot",{format:"png"}); if(s1?.data) writeFileSync("shot-1.10-balance.png",Buffer.from(s1.data,"base64"));
process.exit(0);
