import { writeFileSync } from "node:fs";
const PORT = "9338";
const wait = (ms) => new Promise(r => setTimeout(r, ms));
const list = await (await fetch(`http://127.0.0.1:${PORT}/json/list`)).json();
const page = list.find(t => t.type === "page");
const ws = new WebSocket(page.webSocketDebuggerUrl);
let id = 0; const pending = new Map();
ws.onmessage = e => { const m = JSON.parse(e.data); if (m.id && pending.has(m.id)) { pending.get(m.id)(m.result ?? m.error); pending.delete(m.id); } };
await new Promise(r => ws.onopen = r);
const send = (m, p = {}) => new Promise(res => { const i = ++id; pending.set(i, res); ws.send(JSON.stringify({ id: i, method: m, params: p })); });
const ev = async e => (await send("Runtime.evaluate", { expression: e, returnByValue: true, awaitPromise: true }))?.result?.value;
await wait(800);
console.log("start:", await ev(`JSON.stringify({ v: document.querySelector('.version')?.textContent, title: document.querySelector('.top-title')?.textContent, status: document.querySelector('.statusbar')?.innerText.replace(/\\n/g,' | ').slice(0,120) })`));
await ev(`(() => { const ta = document.querySelector('.composer textarea'); const setter = Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype, 'value').set; setter.call(ta, '输出 1 到 600，每行一个数字'); ta.dispatchEvent(new Event('input', { bubbles: true })); })()`);
await wait(200);
await ev(`document.querySelector('.send-icon:not(.stop)')?.click()`);
for (const t of [1500, 1500, 1500]) { await wait(t); console.log("badge:", await ev(`document.querySelector('.think-badge')?.innerText.replace(/\\n/g,' ') || 'none'`)); }
const shot = await send("Page.captureScreenshot", { format: "png" });
if (shot?.data) writeFileSync("shot-1.15.png", Buffer.from(shot.data, "base64"));
process.exit(0);
